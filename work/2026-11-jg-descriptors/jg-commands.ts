/**
 * Census of the conversation attributes .jg dialogs declare, checked
 * against profiles/winbox-ipc/std-commands.yaml (plan.md step 2).
 *
 *   bun jg-commands.ts <jg-root with one dir per version> <out.md>
 *
 * Command values are classified as std (0xfe0000-0xfe0016, named from
 * std-commands.yaml), none (0xffffffff: the dialog disables that action),
 * or private (handler-local opcodes, listed per route).
 */
import { readFileSync, writeFileSync } from "node:fs";
import YAML from "yaml";
import { CONVERSATION_ATTRS, type JgItem, loadDir } from "./jg-parse.ts";

const [jgRoot, outPath] = process.argv.slice(2) as [string, string];
const VERSIONS = ["6.49.23", "7.25", "7.26beta4"];
const CMD_ATTRS = new Set([
	"getcmd",
	"getallcmd",
	"setcmd",
	"startcmd",
	"pollcmd",
	"cancelcmd",
	"cmd",
]);

const stdDoc = YAML.parse(
	readFileSync(
		new URL("../../profiles/winbox-ipc/std-commands.yaml", import.meta.url),
		"utf8",
	),
) as { commands: Record<string, { "canonical-name"?: string }> };
const STD = new Map<number, string>();
for (const [k, v] of Object.entries(stdDoc.commands))
	STD.set(Number(k), v?.["canonical-name"] ?? "?");

const hex = (n: number) => `0x${n.toString(16)}`;
function classify(n: number): string {
	if (n === 0xffffffff) return "none";
	if (n >= 0xfe0000 && n <= 0xfe00ff)
		return STD.has(n) ? `std ${STD.get(n)}` : `std-unlisted ${hex(n)}`;
	return "private";
}

type Use = {
	route: string;
	dialog: string;
	dtype: string;
	attr: string;
	value: number;
};
function commandUses(items: Map<string, JgItem>): Use[] {
	const out: Use[] = [];
	for (const [route, it] of items) {
		for (const d of it.meta)
			for (const [a, v] of Object.entries(d.attrs))
				if (CMD_ATTRS.has(a) && typeof v === "number")
					out.push({
						route,
						dialog: d.title,
						dtype: d.type,
						attr: a,
						value: v,
					});
		for (const b of it.buttons)
			out.push({
				route: b.path ? JSON.stringify(b.path).replace(/,/g, ", ") : route,
				dialog: `${b.dialog} > ${b.name}`,
				dtype: b.type,
				attr: "cmd",
				value: b.cmd,
			});
	}
	return out;
}

const data = VERSIONS.map((v) => {
	const items = loadDir(`${jgRoot}/${v}`);
	return { v, items, uses: commandUses(items) };
});

let out = `# .jg dialog conversation census

<!-- Generated by jg-commands.ts; do not edit by hand. -->
<!-- cspell:disable -->

Dialog counts by type, then how many dialogs declare each conversation
attribute. Command values are classified against
\`profiles/winbox-ipc/std-commands.yaml\`.

## Dialogs and attributes

| | ${VERSIONS.join(" | ")} |
|---|${VERSIONS.map(() => "---").join("|")}|
`;
const dtypes = new Set<string>();
for (const { items } of data)
	for (const it of items.values()) for (const d of it.meta) dtypes.add(d.type);
for (const t of [...dtypes].sort()) {
	out += `| dialogs: ${t} | ${data.map(({ items }) => [...items.values()].reduce((n, it) => n + it.meta.filter((d) => d.type === t).length, 0)).join(" | ")} |\n`;
}
for (const a of CONVERSATION_ATTRS) {
	out += `| ${a} | ${data.map(({ items }) => [...items.values()].reduce((n, it) => n + it.meta.filter((d) => d.attrs[a] !== undefined).length, 0)).join(" | ")} |\n`;
}
out += `| button cmd (doit etc.) | ${data.map(({ items }) => [...items.values()].reduce((n, it) => n + it.buttons.length, 0)).join(" | ")} |\n`;

out += `\n## Update model of list dialogs (type map)\n\nWebFig always subscribes a list and fetches it with GETALL; \`autorefresh\` adds a timed GETALL (see README, WebFig client model).\n\n| | ${VERSIONS.join(" | ")} |\n|---|${VERSIONS.map(() => "---").join("|")}|\n`;
const maps = (items: Map<string, JgItem>) =>
	[...items.values()].flatMap((it) => it.meta.filter((d) => d.type === "map"));
out += `| map dialogs | ${data.map(({ items }) => maps(items).length).join(" | ")} |\n`;
out += `| with autorefresh | ${data.map(({ items }) => maps(items).filter((d) => d.attrs.autorefresh !== undefined).length).join(" | ")} |\n`;
out += `| autorefresh values (ms) | ${data
	.map(({ items }) => {
		const c = new Map<string, number>();
		for (const d of maps(items))
			if (d.attrs.autorefresh !== undefined)
				c.set(
					String(d.attrs.autorefresh),
					(c.get(String(d.attrs.autorefresh)) ?? 0) + 1,
				);
		return [...c]
			.sort((x, y) => y[1] - x[1])
			.map(([k, n]) => `${k}×${n}`)
			.join(", ");
	})
	.join(" | ")} |\n`;
out += `| refreshfilter values | ${data
	.map(({ items }) => {
		const c = new Map<string, number>();
		for (const d of maps(items))
			if (d.attrs.refreshfilter !== undefined)
				c.set(
					String(d.attrs.refreshfilter),
					(c.get(String(d.attrs.refreshfilter)) ?? 0) + 1,
				);
		return [...c].map(([k, n]) => `${k}×${n}`).join(", ");
	})
	.join(" | ")} |\n`;

out += `\n## Standard commands declared\n\n| attr | value | class | ${VERSIONS.join(" | ")} |\n|---|---|---|${VERSIONS.map(() => "---").join("|")}|\n`;
const keys = new Map<string, Map<string, number>>();
for (const { v, uses } of data)
	for (const u of uses) {
		const c = classify(u.value);
		if (c === "private") continue;
		const k = `${u.attr}|${hex(u.value)}|${c}`;
		const m = keys.get(k) ?? new Map<string, number>();
		m.set(v, (m.get(v) ?? 0) + 1);
		keys.set(k, m);
	}
for (const [k, m] of [...keys].sort()) {
	const [a, val, c] = k.split("|");
	out += `| ${a} | ${val} | ${c} | ${VERSIONS.map((v) => m.get(v) ?? 0).join(" | ")} |\n`;
}

out += `\n## Private (handler-local) commands, 7.25\n\n| route | dialog / control | type | attr | value |\n|---|---|---|---|---|\n`;
const v725 = data.find((d) => d.v === "7.25");
for (const u of (v725?.uses ?? [])
	.filter((x) => classify(x.value) === "private")
	.sort((a, b) => a.route.localeCompare(b.route) || a.value - b.value))
	out += `| ${u.route} | ${u.dialog.replaceAll("|", "\\|")} | ${u.dtype} | ${u.attr} | ${u.value} (${hex(u.value)}) |\n`;
writeFileSync(outPath, out);
console.log(out.split("\n").slice(9, 40).join("\n"));
